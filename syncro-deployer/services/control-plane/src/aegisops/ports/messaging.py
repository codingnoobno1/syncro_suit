"""Hexagonal Ports for Tri-Broker Messaging (Kafka, RabbitMQ, Redis)."""

from __future__ import annotations

from collections.abc import AsyncIterator
from typing import Any, Protocol

from aegisops.domain.models import CloudEvent, QueueJob


class EventBusPort(Protocol):
    """Kafka-compatible immutable CloudEvents audit and telemetry stream."""

    async def publish(self, topic: str, event: CloudEvent) -> CloudEvent: ...
    async def list_events(self, topic: str | None = None, limit: int = 50) -> list[CloudEvent]: ...
    async def health(self) -> dict[str, Any]: ...


class JobQueuePort(Protocol):
    """RabbitMQ-compatible priority work queue with Dead Letter Queue."""

    async def enqueue(self, job: QueueJob) -> QueueJob: ...
    async def dequeue(self, queue: str) -> QueueJob | None: ...
    async def complete(self, job_id: str, result: dict[str, Any]) -> QueueJob: ...
    async def fail(self, job_id: str, error: str, dead_letter: bool = False) -> QueueJob: ...
    async def list_jobs(self, queue: str | None = None, limit: int = 50) -> list[QueueJob]: ...
    async def health(self) -> dict[str, Any]: ...


class StateStorePort(Protocol):
    """Redis-compatible distributed lock manager, TTL registry, cache, and Pub/Sub."""

    async def acquire_lock(self, key: str, owner: str, ttl_seconds: int = 60) -> bool: ...
    async def release_lock(self, key: str, owner: str) -> bool: ...
    async def set_value(self, key: str, value: Any, ttl_seconds: int | None = None) -> None: ...
    async def get_value(self, key: str) -> Any | None: ...
    async def delete_key(self, key: str) -> None: ...
    async def get_ttl(self, key: str) -> int | None: ...
    async def publish_channel(self, channel: str, payload: dict[str, Any]) -> None: ...
    def subscribe_channel(self, channel: str) -> AsyncIterator[dict[str, Any]]: ...
    async def health(self) -> dict[str, Any]: ...
